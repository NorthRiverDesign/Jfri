using System.Text;
using Jfri.Core.Analysis;
using Jfri.Core.Planning;

namespace Jfri.Core.Generation;

/// <summary>
/// Renders the plan as a Docker Compose project behind Caddy (automatic HTTPS). Databases sit on
/// an internal network with no published ports, secrets live in 0600 env files, logs are
/// rotated, and a backup container dumps the database nightly.
/// </summary>
public static class ComposeGenerator
{
	const string Dir = "compose";

	public static List<Artifact> Generate(DeploymentPlan plan, RenderContext context)
	{
		var files = new List<Artifact>
		{
			new($"{Dir}/compose.yaml", Compose(plan, context)),
			new($"{Dir}/app.env", AppEnv(plan, context), "0600", Sensitive: true),
			new($"{Dir}/Caddyfile", Caddyfile(plan, context)),
			new($"{Dir}/deploy.sh", DeployScript(plan, context), "0755"),
		};
		foreach (var service in plan.Services)
		{
			files.Add(new($"{Dir}/{service.Name}.env", ServiceEnv(service, context), "0600", Sensitive: true));
		}
		if (plan.Cache is not null)
		{
			files.Add(new($"{Dir}/.env", $"REDIS_PASSWORD={EnvValue(Template.Resolve("{{secret:REDIS_PASSWORD}}", context))}\n", "0600", Sensitive: true));
		}
		return files;
	}

	static string Compose(DeploymentPlan plan, RenderContext context)
	{
		var sb = new StringBuilder();
		sb.AppendLine($"# {plan.AppName}: generated by Jfri. Start with ./deploy.sh");
		sb.AppendLine($"name: {plan.AppName}");
		sb.AppendLine();
		sb.AppendLine("x-logging: &logging");
		sb.AppendLine("  driver: json-file");
		sb.AppendLine("  options:");
		sb.AppendLine("    max-size: \"10m\"");
		sb.AppendLine("    max-file: \"5\"");
		sb.AppendLine();
		sb.AppendLine("services:");
		foreach (var process in plan.Processes)
		{
			AppService(sb, plan, context, process.Name, process.Command, process.Kind, process.Resources, releaseProfile: false);
		}
		if (plan.ReleaseCommand is not null)
		{
			AppService(sb, plan, context, "release", plan.ReleaseCommand, ProcessKind.Worker, new Resources(100, 256, 1000, 1024), releaseProfile: true);
		}
		foreach (var service in plan.Services)
		{
			var args = ServiceRecipes.Args(service, kubernetes: false);
			sb.AppendLine($"  {service.Name}:");
			sb.AppendLine($"    image: {service.Image}");
			sb.AppendLine("    restart: unless-stopped");
			sb.AppendLine($"    env_file: [\"{service.Name}.env\"]");
			if (service.Kind == ServiceKind.Redis)
			{
				// ${REDIS_PASSWORD} is interpolated by Compose from the project's 0600 .env file; exec form keeps
				// the image entrypoint, which drops root before starting the server.
				sb.AppendLine($"    command: {Yaml.List(["valkey-server", .. args!])}");
			}
			else if (args is not null)
			{
				sb.AppendLine($"    command: {Yaml.List(args.Select(Escape))}");
			}
			sb.AppendLine("    volumes:");
			sb.AppendLine($"      - {service.Name}-data:{service.DataPath}");
			sb.AppendLine("    networks: [\"internal\"]");
			sb.AppendLine("    healthcheck:");
			sb.AppendLine($"      test: {Yaml.List(["CMD-SHELL", Escape(ServiceRecipes.Ready(service))])}");
			sb.AppendLine("      interval: 10s");
			sb.AppendLine("      timeout: 5s");
			sb.AppendLine("      retries: 10");
			sb.AppendLine("      start_period: 30s");
			sb.AppendLine("    security_opt: [\"no-new-privileges:true\"]");
			sb.AppendLine($"    mem_limit: {service.Resources.MemoryLimit}m");
			sb.AppendLine("    logging: *logging");
		}
		if (plan.Backups.Enabled)
		{
			foreach (var service in plan.Services.Where(s => s.IsDatabase))
			{
				var command = ServiceRecipes.BackupCommand(service, plan.Backups.RetentionDays);
				if (command is null)
				{
					continue;
				}
				BackupService(sb, plan.AppName, $"backup-{service.Name}", service.Image, command, $"{service.Name}.env", null, service.Name);
			}
			var sqliteVolume = plan.Volumes.FirstOrDefault(v => v.Reason.Contains("SQLite", StringComparison.Ordinal));
			if (sqliteVolume is not null)
			{
				BackupService(sb, plan.AppName, "backup-sqlite", "alpine:3", ServiceRecipes.SqliteBackupCommand(plan.Backups.RetentionDays), null, sqliteVolume.Name, null);
			}
		}
		sb.AppendLine("  caddy:");
		sb.AppendLine("    image: caddy:2-alpine");
		sb.AppendLine("    restart: unless-stopped");
		sb.AppendLine("    ports:");
		sb.AppendLine("      - \"80:80\"");
		sb.AppendLine("      - \"443:443\"");
		sb.AppendLine("      - \"443:443/udp\"");
		sb.AppendLine("    volumes:");
		sb.AppendLine("      - ./Caddyfile:/etc/caddy/Caddyfile:ro");
		sb.AppendLine("      - caddy-data:/data");
		sb.AppendLine("      - caddy-config:/config");
		sb.AppendLine("    networks: [\"edge\"]");
		if (plan.Web is not null)
		{
			sb.AppendLine("    depends_on: [\"web\"]");
		}
		sb.AppendLine("    logging: *logging");
		sb.AppendLine();
		sb.AppendLine("networks:");
		sb.AppendLine("  edge: {}");
		sb.AppendLine("  internal:");
		sb.AppendLine("    internal: true");
		sb.AppendLine();
		sb.AppendLine("volumes:");
		sb.AppendLine("  caddy-data: {}");
		sb.AppendLine("  caddy-config: {}");
		foreach (var service in plan.Services)
		{
			sb.AppendLine($"  {service.Name}-data: {{}}");
		}
		foreach (var volume in plan.Volumes)
		{
			sb.AppendLine($"  {volume.Name}: {{}}");
		}
		return sb.ToString();
	}

	static void AppService(StringBuilder sb, DeploymentPlan plan, RenderContext context, string name, string? command, ProcessKind kind, Resources resources, bool releaseProfile)
	{
		sb.AppendLine($"  {name}:");
		sb.AppendLine($"    image: {plan.ImageRepository}:${{JFRI_REVISION:-{context.Revision}}}");
		if (releaseProfile)
		{
			sb.AppendLine("    profiles: [\"release\"]");
			sb.AppendLine("    restart: \"no\"");
		}
		else
		{
			sb.AppendLine("    restart: unless-stopped");
		}
		if (command is not null)
		{
			// Long-running processes exec so signals reach them; release commands may be compound (a && b).
			sb.AppendLine($"    command: {Yaml.Shell(Escape(releaseProfile ? command : "exec " + command))}");
		}
		sb.AppendLine("    env_file: [\"app.env\"]");
		if (plan.Volumes.Count > 0)
		{
			sb.AppendLine("    volumes:");
			foreach (var volume in plan.Volumes)
			{
				sb.AppendLine($"      - {volume.Name}:{volume.MountPath}");
			}
		}
		// "internal" reaches the database; "edge" is how Caddy reaches the app and the app reaches the internet.
		sb.AppendLine("    networks: [\"internal\", \"edge\"]");
		if (plan.Services.Count > 0)
		{
			sb.AppendLine("    depends_on:");
			foreach (var service in plan.Services)
			{
				sb.AppendLine($"      {service.Name}:");
				sb.AppendLine("        condition: service_healthy");
			}
		}
		sb.AppendLine("    security_opt: [\"no-new-privileges:true\"]");
		sb.AppendLine($"    mem_limit: {resources.MemoryLimit}m");
		if (kind == ProcessKind.Scheduler)
		{
			sb.AppendLine("    stop_grace_period: 90s");
		}
		sb.AppendLine("    logging: *logging");
	}

	static void BackupService(StringBuilder sb, string appName, string name, string image, string command, string? envFile, string? dataVolume, string? dependsOn)
	{
		// A tiny scheduler loop: run at 03:15 UTC every day (compose has no cron).
		var loop = "while true; do now=$(date -u +%s); next=$(date -u -d \"$(date -u +%Y-%m-%d) 03:15\" +%s 2>/dev/null || echo $((now + 86400))); "
			+ "[ \"$next\" -le \"$now\" ] && next=$((next + 86400)); sleep $((next - now)); "
			+ $"( {command} ) || echo \"backup failed\" >&2; done";
		sb.AppendLine($"  {name}:");
		sb.AppendLine($"    image: {image}");
		sb.AppendLine("    restart: unless-stopped");
		sb.AppendLine($"    entrypoint: {Yaml.List(["sh", "-c", Escape(loop)])}");
		if (envFile is not null)
		{
			sb.AppendLine($"    env_file: [\"{envFile}\"]");
		}
		sb.AppendLine("    environment:");
		sb.AppendLine("      TZ: UTC");
		sb.AppendLine("    volumes:");
		sb.AppendLine($"      - /var/lib/jfri/backups/{appName}:/backups");
		if (dataVolume is not null)
		{
			sb.AppendLine($"      - {dataVolume}:/data:ro");
		}
		// SQLite backups install the sqlite3 tool at run time, so they need the outbound (edge) network.
		sb.AppendLine(dataVolume is null ? "    networks: [\"internal\"]" : "    networks: [\"edge\"]");
		if (dependsOn is not null)
		{
			sb.AppendLine($"    depends_on: [\"{dependsOn}\"]");
		}
		sb.AppendLine("    security_opt: [\"no-new-privileges:true\"]");
		sb.AppendLine("    logging: *logging");
	}

	static string AppEnv(DeploymentPlan plan, RenderContext context)
	{
		var sb = new StringBuilder();
		sb.AppendLine("# App settings. Contains secrets: mode 0600, never commit.");
		foreach (var env in plan.Environment)
		{
			sb.AppendLine($"{env.Key}={EnvValue(Template.Resolve(env.Value, context))}");
		}
		return sb.ToString();
	}

	static string ServiceEnv(PlannedService service, RenderContext context)
	{
		var sb = new StringBuilder();
		foreach (var (key, value) in ServiceRecipes.Environment(service).Concat(ServiceRecipes.BackupEnvironment(service)).DistinctBy(e => e.Key))
		{
			sb.AppendLine($"{key}={EnvValue(Template.Resolve(value, context))}");
		}
		return sb.ToString();
	}

	/// <summary>Compose interpolates $VAR in the file itself; $$ passes a literal $ through to the container's shell.</summary>
	static string Escape(string value) => value.Replace("$", "$$", StringComparison.Ordinal);

	/// <summary>
	/// Writes a value so Compose reads it back exactly. Unquoted env-file values get $VAR interpolated,
	/// " #" comments cut off and surrounding spaces trimmed; single-quoted values are literal (except \'), and
	/// double-quoted ones take \\, \" and $$ escapes. Newlines are refused so a value can't inject
	/// another variable.
	/// </summary>
	public static string EnvValue(string value)
	{
		if (value.Contains('\n') || value.Contains('\r'))
		{
			throw new InvalidOperationException("Environment values can't contain newlines.");
		}
		if (value.Length > 0 && value.All(c => char.IsAsciiLetterOrDigit(c) || c is '_' or '-' or '.' or ':' or '/' or '@' or '+' or '=' or ',' or '%' or '~' or '?' or '&'))
		{
			return value;
		}
		// Inside single quotes \' still ends up escaping the quote, so values with a backslash take the double-quoted form.
		if (!value.Contains('\'') && !value.Contains('\\'))
		{
			return $"'{value}'";
		}
		return "\"" + value.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal).Replace("$", "$$", StringComparison.Ordinal) + "\"";
	}

	public static string Caddyfile(DeploymentPlan plan, RenderContext context)
	{
		var sb = new StringBuilder();
		if (plan.AcmeEmail is not null)
		{
			sb.AppendLine("{");
			sb.AppendLine($"\temail {plan.AcmeEmail}");
			sb.AppendLine("}");
			sb.AppendLine();
		}
		sb.AppendLine($"{context.Host} {{");
		sb.AppendLine("\tencode zstd gzip");
		sb.AppendLine("\theader {");
		sb.AppendLine("\t\tStrict-Transport-Security \"max-age=31536000\"");
		sb.AppendLine("\t\tX-Content-Type-Options \"nosniff\"");
		sb.AppendLine("\t\tReferrer-Policy \"strict-origin-when-cross-origin\"");
		sb.AppendLine("\t\t-Server");
		sb.AppendLine("\t}");
		sb.AppendLine($"\treverse_proxy web:{plan.App.Port} {{");
		if (plan.App.HealthCheckPath is { } health)
		{
			sb.AppendLine($"\t\thealth_uri {health}");
			sb.AppendLine("\t\thealth_interval 30s");
		}
		sb.AppendLine("\t\tlb_try_duration 30s");
		sb.AppendLine("\t}");
		sb.AppendLine("}");
		return sb.ToString();
	}

	static string DeployScript(DeploymentPlan plan, RenderContext context)
	{
		var sb = new StringBuilder();
		sb.AppendLine("#!/usr/bin/env bash");
		sb.AppendLine($"# Starts {plan.AppName} revision {context.Revision}. Safe to re-run.");
		sb.AppendLine("set -euo pipefail");
		sb.AppendLine("cd \"$(dirname \"$0\")\"");
		sb.AppendLine($"export JFRI_REVISION=\"${{JFRI_REVISION:-{context.Revision}}}\"");
		sb.AppendLine($"mkdir -p /var/lib/jfri/backups/{plan.AppName}");
		if (plan.Services.Count > 0)
		{
			sb.AppendLine($"docker compose up -d --wait {string.Join(' ', plan.Services.Select(s => s.Name))}");
		}
		if (plan.ReleaseCommand is not null)
		{
			sb.AppendLine("echo \"Running release command...\"");
			sb.AppendLine("docker compose run --rm -T release");
		}
		sb.AppendLine("docker compose up -d --remove-orphans --wait");
		sb.AppendLine("docker image prune -f --filter \"until=168h\" >/dev/null || true");
		sb.AppendLine("echo \"Deployed.\"");
		return sb.ToString();
	}
}
