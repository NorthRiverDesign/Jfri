using System.Text;
using Jfri.Core.Analysis;
using Jfri.Core.Planning;

namespace Jfri.Core.Generation;

/// <summary>
/// A GitHub Actions workflow: run the repo's tests and check the image builds on every push and
/// pull request, then ask Jfri to deploy main through an HMAC-signed webhook. Jfri keeps the
/// server credentials, so the repository never holds SSH keys or cloud tokens.
/// </summary>
public static class CiGenerator
{
	public const string Path = ".github/workflows/jfri.yml";

	public static string Generate(DeploymentPlan plan, string branch = "main")
	{
		var app = plan.App;
		var dir = string.IsNullOrEmpty(app.RootPath) || app.Stack == Stack.DotNet ? "." : app.RootPath;
		var sb = new StringBuilder();
		sb.AppendLine("# Generated by Jfri. Tests every push; deploys main through Jfri once tests pass.");
		sb.AppendLine("# Repository secrets needed: JFRI_DEPLOY_URL and JFRI_WEBHOOK_SECRET (shown on the app's page in Jfri).");
		sb.AppendLine("name: CI");
		sb.AppendLine();
		sb.AppendLine("on:");
		sb.AppendLine("  push:");
		sb.AppendLine($"    branches: [{Yaml.Q(branch)}]");
		sb.AppendLine("  pull_request:");
		sb.AppendLine();
		sb.AppendLine("permissions:");
		sb.AppendLine("  contents: read");
		sb.AppendLine();
		sb.AppendLine("concurrency:");
		sb.AppendLine("  group: ci-${{ github.ref }}");
		sb.AppendLine("  cancel-in-progress: true");
		sb.AppendLine();
		sb.AppendLine("jobs:");
		sb.AppendLine("  test:");
		sb.AppendLine("    runs-on: ubuntu-latest");
		sb.AppendLine("    steps:");
		sb.AppendLine("      - uses: actions/checkout@v4");
		foreach (var line in Setup(app, dir))
		{
			sb.AppendLine("      " + line);
		}
		if (app.TestCommand is not null)
		{
			sb.AppendLine("      - name: Test");
			if (dir != ".")
			{
				sb.AppendLine($"        working-directory: {dir}");
			}
			sb.AppendLine($"        run: {app.TestCommand}");
		}
		sb.AppendLine("      - name: Build the container image");
		var dockerfile = app.BuildStrategy == BuildStrategy.ExistingDockerfile ? app.DockerfilePath! : RepoFiles.Join(plan.BuildContext, "Dockerfile");
		var context = string.IsNullOrEmpty(plan.BuildContext) ? "." : plan.BuildContext;
		sb.AppendLine($"        run: docker build -f {dockerfile} -t {plan.ImageRepository}:ci {context}");
		sb.AppendLine();
		sb.AppendLine("  deploy:");
		sb.AppendLine("    needs: test");
		sb.AppendLine($"    if: github.event_name == 'push' && github.ref == 'refs/heads/{branch}'");
		sb.AppendLine("    runs-on: ubuntu-latest");
		sb.AppendLine("    steps:");
		sb.AppendLine("      - name: Ask Jfri to deploy this commit");
		sb.AppendLine("        env:");
		sb.AppendLine("          JFRI_DEPLOY_URL: ${{ secrets.JFRI_DEPLOY_URL }}");
		sb.AppendLine("          JFRI_WEBHOOK_SECRET: ${{ secrets.JFRI_WEBHOOK_SECRET }}");
		sb.AppendLine("        run: |");
		sb.AppendLine("          body=$(printf '{\"ref\":\"%s\",\"after\":\"%s\"}' \"$GITHUB_REF\" \"$GITHUB_SHA\")");
		sb.AppendLine("          sig=$(printf '%s' \"$body\" | openssl dgst -sha256 -hmac \"$JFRI_WEBHOOK_SECRET\" -r | cut -d' ' -f1)");
		sb.AppendLine("          curl -fsS -X POST \"$JFRI_DEPLOY_URL\" -H 'Content-Type: application/json' -H \"X-Hub-Signature-256: sha256=$sig\" --data \"$body\"");
		return sb.ToString();
	}

	static IEnumerable<string> Setup(AppProfile app, string dir)
	{
		var wd = dir == "." ? "" : $"\n  working-directory: {dir}";
		switch (app.Stack)
		{
			case Stack.DotNet:
				yield return "- uses: actions/setup-dotnet@v4";
				yield return "  with:";
				yield return $"    dotnet-version: \"{app.RuntimeVersion}.x\"";
				break;
			case Stack.Php:
				yield return "- uses: shivammathur/setup-php@v2";
				yield return "  with:";
				yield return $"    php-version: \"{app.RuntimeVersion}\"";
				yield return $"- run: composer install --no-interaction --prefer-dist{Indent(wd)}";
				if (app.Framework == "Laravel")
				{
					yield return $"- run: cp -n .env.example .env && php artisan key:generate || true{Indent(wd)}";
				}
				break;
			case Stack.Node:
			case Stack.Static when app.BuildCommand is not null:
				yield return "- uses: actions/setup-node@v4";
				yield return "  with:";
				yield return $"    node-version: \"{app.RuntimeVersion ?? RuntimeDefaults.Node}\"";
				var install = app.PackageManager switch
				{
					"pnpm" => "corepack enable && pnpm install --frozen-lockfile",
					"yarn" => "corepack enable && yarn install --frozen-lockfile",
					"bun" => "npm install -g bun && bun install",
					_ => "npm ci",
				};
				yield return $"- run: {install}{Indent(wd)}";
				break;
			case Stack.Python:
				yield return "- uses: actions/setup-python@v5";
				yield return "  with:";
				yield return $"    python-version: \"{app.RuntimeVersion}\"";
				var pip = app.PackageManager switch
				{
					"poetry" => "pip install poetry && poetry install",
					"uv" => "pip install uv && uv sync",
					"pipenv" => "pip install pipenv && pipenv install --dev --system",
					_ => "pip install -r requirements.txt",
				};
				yield return $"- run: {pip}{Indent(wd)}";
				break;
			case Stack.Ruby:
				yield return "- uses: ruby/setup-ruby@v1";
				yield return "  with:";
				yield return "    bundler-cache: true";
				break;
			case Stack.Go:
				yield return "- uses: actions/setup-go@v5";
				yield return "  with:";
				yield return "    go-version-file: go.mod";
				break;
			case Stack.Java:
				yield return "- uses: actions/setup-java@v4";
				yield return "  with:";
				yield return "    distribution: temurin";
				yield return $"    java-version: \"{app.RuntimeVersion}\"";
				break;
		}
	}

	static string Indent(string text) => text.Replace("\n", "\n      ", StringComparison.Ordinal);
}
