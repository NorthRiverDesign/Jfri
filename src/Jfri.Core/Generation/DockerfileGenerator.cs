using System.Text;
using Jfri.Core.Analysis;
using Jfri.Core.Planning;

namespace Jfri.Core.Generation;

/// <summary>
/// Writes a production Dockerfile for the detected stack: multi-stage, official or widely trusted
/// base images pinned to the runtime line the repo asks for, dependencies cached in their own
/// layer, and a non-root runtime user.
/// </summary>
public static class DockerfileGenerator
{
	/// <summary>The numeric UID the generated image runs as (used for runAsUser / volume ownership).</summary>
	public static int RuntimeUid(AppProfile app) => app.BuildStrategy == BuildStrategy.ExistingDockerfile ? 0 : app.Stack switch
	{
		Stack.DotNet => 1654,
		Stack.Php => 33,
		Stack.Node => 1000,
		Stack.Static => 101,
		Stack.Go => 65532,
		Stack.Ruby => 1000,
		_ => 10001,
	};

	public static string Generate(DeploymentPlan plan)
	{
		var app = plan.App;
		var sb = new StringBuilder();
		sb.AppendLine("# syntax=docker/dockerfile:1");
		sb.AppendLine($"# Generated by Jfri for {app.Framework ?? app.Stack.ToString()} ({app.Stack} {app.RuntimeVersion}). Commit it and edit freely:");
		sb.AppendLine("# once a Dockerfile exists in the repository, Jfri uses it instead of generating one.");
		sb.AppendLine();
		var body = app.Stack switch
		{
			Stack.DotNet => DotNet(plan),
			Stack.Php => Php(plan),
			Stack.Node => Node(plan),
			Stack.Python => Python(plan),
			Stack.Ruby => Ruby(plan),
			Stack.Go => Go(plan),
			Stack.Java => Java(plan),
			Stack.Static => Static(plan),
			_ => throw new NotSupportedException($"Jfri can't generate a Dockerfile for {app.Stack}; add one to the repository."),
		};
		sb.Append(body);
		return sb.ToString();
	}

	public static string DockerIgnore(DeploymentPlan plan)
	{
		var lines = new List<string>
		{
			".git", ".github", ".gitlab-ci.yml", ".vscode", ".idea", "*.md", "!README.md", "Dockerfile*", ".dockerignore",
			"docker-compose*.yml", "compose*.yaml", ".env", ".env.*", "!.env.example", "*.log", "coverage", ".jfri",
		};
		lines.AddRange(plan.App.Stack switch
		{
			Stack.DotNet => ["**/bin", "**/obj", "**/TestResults", "*.user"],
			Stack.Php => ["vendor", "node_modules", "storage/logs/*", "storage/framework/cache/data/*", "storage/framework/sessions/*", "storage/framework/views/*", "bootstrap/cache/*.php", "public/hot", "public/storage", "tests"],
			Stack.Node or Stack.Static => ["node_modules", ".next", ".nuxt", ".output", "dist", "build"],
			Stack.Python => ["__pycache__", "*.pyc", ".venv", "venv", ".pytest_cache", ".mypy_cache"],
			Stack.Ruby => ["log/*", "tmp/*", "storage/*", "vendor/bundle", "node_modules"],
			Stack.Go => ["bin", "vendor"],
			Stack.Java => ["target", "build", ".gradle"],
			_ => [],
		});
		return string.Join('\n', lines) + "\n";
	}

	static string DotNet(DeploymentPlan plan)
	{
		var app = plan.App;
		var version = app.RuntimeVersion ?? RuntimeDefaults.DotNet;
		var project = app.EntryProject ?? throw new InvalidOperationException("No .NET entry project.");
		var dll = app.StartCommand?.Split(' ').Last() ?? "app.dll";
		var portEnv = VersionRange.ParseVersion(version).Major >= 8 ? "ASPNETCORE_HTTP_PORTS=8080" : "ASPNETCORE_URLS=http://+:8080";
		var dirs = MkdirFor(plan, "app");
		return $"""
			FROM mcr.microsoft.com/dotnet/sdk:{version} AS build
			WORKDIR /src
			COPY . .
			RUN --mount=type=cache,id=nuget,target=/root/.nuget/packages \
			    dotnet publish "{project}" -c Release -o /app/publish /p:UseAppHost=false

			FROM mcr.microsoft.com/dotnet/aspnet:{version} AS runtime
			WORKDIR /app
			ENV {portEnv} \
			    DOTNET_gcServer=0
			COPY --from=build /app/publish .
			{dirs}USER $APP_UID
			EXPOSE 8080
			ENTRYPOINT ["dotnet", "{dll}"]

			""";
	}

	static string Php(DeploymentPlan plan)
	{
		var app = plan.App;
		var version = app.RuntimeVersion ?? RuntimeDefaults.Php;
		var webroot = string.IsNullOrEmpty(app.DocumentRoot) ? "/var/www/html" : $"/var/www/html/{app.DocumentRoot}";
		var laravel = app.Framework == "Laravel";
		var sb = new StringBuilder();
		sb.AppendLine($"FROM serversideup/php:{version}-fpm-nginx AS base");
		sb.AppendLine("ENV PHP_OPCACHE_ENABLE=1 \\");
		sb.AppendLine($"    NGINX_WEBROOT={webroot}");
		sb.AppendLine("WORKDIR /var/www/html");
		sb.AppendLine();
		sb.AppendLine("FROM base AS vendor");
		sb.AppendLine("COPY --chown=www-data:www-data composer.json composer.lock* ./");
		sb.AppendLine("RUN composer install --no-dev --no-interaction --no-scripts --no-autoloader --prefer-dist");
		sb.AppendLine();
		var assets = app.AssetBuildCommand is not null;
		if (assets)
		{
			sb.AppendLine($"FROM node:{RuntimeDefaults.Node}-slim AS assets");
			sb.AppendLine("WORKDIR /app");
			sb.AppendLine("COPY package.json package-lock.json* yarn.lock* pnpm-lock.yaml* ./");
			sb.AppendLine("RUN corepack enable && if [ -f pnpm-lock.yaml ]; then pnpm install --frozen-lockfile; elif [ -f yarn.lock ]; then yarn install --frozen-lockfile; elif [ -f package-lock.json ]; then npm ci; else npm install; fi");
			sb.AppendLine("COPY . .");
			sb.AppendLine("COPY --from=vendor /var/www/html/vendor ./vendor");
			sb.AppendLine($"RUN {app.AssetBuildCommand}");
			sb.AppendLine();
		}
		sb.AppendLine("FROM base AS app");
		sb.AppendLine("COPY --chown=www-data:www-data --from=vendor /var/www/html/vendor ./vendor");
		sb.AppendLine("COPY --chown=www-data:www-data . .");
		if (assets)
		{
			sb.AppendLine($"COPY --chown=www-data:www-data --from=assets /app/{(string.IsNullOrEmpty(app.DocumentRoot) ? "" : app.DocumentRoot + "/")}build ./{(string.IsNullOrEmpty(app.DocumentRoot) ? "" : app.DocumentRoot + "/")}build");
		}
		if (laravel)
		{
			sb.AppendLine("RUN composer dump-autoload --optimize --no-dev --no-scripts \\");
			sb.AppendLine("    && mkdir -p storage/app/public storage/framework/cache storage/framework/sessions storage/framework/views storage/logs bootstrap/cache database/data \\");
			sb.AppendLine("    && php artisan package:discover --ansi \\");
			sb.AppendLine("    && ln -sfn ../storage/app/public public/storage");
		}
		else
		{
			sb.AppendLine("RUN if [ -f composer.json ]; then composer dump-autoload --optimize --no-dev --no-scripts; fi");
		}
		var dirs = MkdirFor(plan, "www-data");
		if (dirs.Length > 0)
		{
			sb.Append(dirs);
		}
		sb.AppendLine("EXPOSE 8080");
		return sb.ToString();
	}

	static string Node(DeploymentPlan plan)
	{
		var app = plan.App;
		var version = app.RuntimeVersion ?? RuntimeDefaults.Node;
		var pm = app.PackageManager ?? "npm";
		var install = pm switch
		{
			"pnpm" => "corepack enable && pnpm install --frozen-lockfile",
			"yarn" => "corepack enable && (yarn install --immutable 2>/dev/null || yarn install --frozen-lockfile)",
			"bun" => "npm install -g bun && bun install --frozen-lockfile",
			_ => "if [ -f package-lock.json ]; then npm ci; else npm install; fi",
		};
		var prune = pm switch
		{
			"npm" => "RUN npm prune --omit=dev\n",
			_ => "",
		};
		var nextStandalone = app.Framework == "Next.js" && app.StartCommand == "node server.js";
		var dirs = MkdirFor(plan, "node");
		var sb = new StringBuilder();
		sb.AppendLine($"FROM node:{version}-slim AS deps");
		sb.AppendLine("WORKDIR /app");
		sb.AppendLine("COPY package.json package-lock.json* yarn.lock* pnpm-lock.yaml* bun.lock* bun.lockb* .npmrc* ./");
		sb.AppendLine($"RUN {install}");
		sb.AppendLine();
		sb.AppendLine("FROM deps AS build");
		sb.AppendLine("COPY . .");
		sb.AppendLine("ENV NODE_ENV=production");
		if (app.BuildCommand is not null)
		{
			sb.AppendLine($"RUN {app.BuildCommand}");
		}
		if (!nextStandalone)
		{
			sb.Append(prune);
		}
		sb.AppendLine();
		sb.AppendLine($"FROM node:{version}-slim AS runtime");
		sb.AppendLine("WORKDIR /app");
		sb.AppendLine($"ENV NODE_ENV=production \\\n    PORT={app.Port} \\\n    HOSTNAME=0.0.0.0");
		if (nextStandalone)
		{
			sb.AppendLine("COPY --from=build --chown=node:node /app/public ./public");
			sb.AppendLine("COPY --from=build --chown=node:node /app/.next/standalone ./");
			sb.AppendLine("COPY --from=build --chown=node:node /app/.next/static ./.next/static");
		}
		else
		{
			sb.AppendLine("COPY --from=build --chown=node:node /app ./");
		}
		sb.Append(dirs);
		sb.AppendLine("USER node");
		sb.AppendLine($"EXPOSE {app.Port}");
		sb.AppendLine($"HEALTHCHECK --interval=30s --timeout=5s --start-period=30s CMD node -e \"fetch('http://127.0.0.1:{app.Port}{app.HealthCheckPath ?? "/"}').then(r => process.exit(r.status < 500 ? 0 : 1)).catch(() => process.exit(1))\"");
		sb.AppendLine($"CMD {ExecForm(app.StartCommand ?? "npm start")}");
		return sb.ToString();
	}

	static string Python(DeploymentPlan plan)
	{
		var app = plan.App;
		var version = app.RuntimeVersion ?? RuntimeDefaults.Python;
		var install = app.PackageManager switch
		{
			"uv" => "COPY --from=ghcr.io/astral-sh/uv:latest /uv /usr/local/bin/uv\nCOPY pyproject.toml uv.lock ./\nRUN uv export --frozen --no-dev --no-hashes -o requirements.txt && pip install -r requirements.txt",
			"poetry" => "COPY pyproject.toml poetry.lock ./\nRUN pip install poetry poetry-plugin-export && poetry export --only main -f requirements.txt -o requirements.txt --without-hashes && pip install -r requirements.txt",
			"pipenv" => "COPY Pipfile Pipfile.lock* ./\nRUN pip install pipenv && pipenv install --system --deploy",
			_ => "COPY requirements.txt ./\nRUN pip install -r requirements.txt",
		};
		var server = app.StartCommand?.Split(' ')[0] ?? "gunicorn";
		var dirs = MkdirFor(plan, "app");
		var sb = new StringBuilder();
		sb.AppendLine($"FROM python:{version}-slim");
		sb.AppendLine("ENV PYTHONDONTWRITEBYTECODE=1 \\\n    PYTHONUNBUFFERED=1 \\\n    PIP_NO_CACHE_DIR=1 \\\n    PIP_DISABLE_PIP_VERSION_CHECK=1");
		sb.AppendLine("WORKDIR /app");
		sb.AppendLine("RUN useradd --create-home --uid 10001 app");
		sb.AppendLine(install);
		sb.AppendLine($"RUN pip install {(server == "uvicorn" ? "\"uvicorn[standard]\"" : "gunicorn")}");
		sb.AppendLine("COPY . .");
		if (app.Framework == "Django")
		{
			sb.AppendLine("RUN DJANGO_SECRET_KEY=build-only SECRET_KEY=build-only python manage.py collectstatic --noinput \\");
			sb.AppendLine("    || echo \"collectstatic failed; configure STATIC_ROOT (and WhiteNoise) to serve static files\" >&2");
		}
		sb.Append(dirs);
		sb.AppendLine("USER 10001");
		sb.AppendLine($"EXPOSE {app.Port}");
		sb.AppendLine($"HEALTHCHECK --interval=30s --timeout=5s --start-period=30s CMD python -c \"import urllib.request,sys; urllib.request.urlopen('http://127.0.0.1:{app.Port}{app.HealthCheckPath ?? "/"}', timeout=4)\" || exit 1");
		sb.AppendLine($"CMD {ExecForm(app.StartCommand ?? "gunicorn app:app --bind 0.0.0.0:8000")}");
		return sb.ToString();
	}

	static string Ruby(DeploymentPlan plan)
	{
		var app = plan.App;
		var version = app.RuntimeVersion ?? RuntimeDefaults.Ruby;
		var db = plan.Database?.Kind;
		var (buildLibs, runtimeLibs) = db switch
		{
			ServiceKind.PostgreSql => ("libpq-dev", "libpq5"),
			ServiceKind.MySql or ServiceKind.MariaDb => ("default-libmysqlclient-dev", "default-mysql-client"),
			_ => ("libsqlite3-dev", "libsqlite3-0"),
		};
		var dirs = MkdirFor(plan, "rails");
		return $"""
			FROM ruby:{version}-slim AS build
			RUN apt-get update -qq && apt-get install --no-install-recommends -y build-essential git pkg-config libyaml-dev {buildLibs} && rm -rf /var/lib/apt/lists/*
			WORKDIR /rails
			ENV RAILS_ENV=production \
			    BUNDLE_DEPLOYMENT=1 \
			    BUNDLE_WITHOUT="development:test" \
			    BUNDLE_PATH=/usr/local/bundle
			COPY Gemfile Gemfile.lock ./
			RUN bundle install && rm -rf ~/.bundle "$BUNDLE_PATH"/ruby/*/cache
			COPY . .
			RUN if [ -f bin/rails ]; then SECRET_KEY_BASE_DUMMY=1 bin/rails assets:precompile || true; fi

			FROM ruby:{version}-slim
			RUN apt-get update -qq && apt-get install --no-install-recommends -y curl libyaml-0-2 {runtimeLibs} && rm -rf /var/lib/apt/lists/*
			WORKDIR /rails
			ENV RAILS_ENV=production \
			    BUNDLE_DEPLOYMENT=1 \
			    BUNDLE_WITHOUT="development:test" \
			    BUNDLE_PATH=/usr/local/bundle
			COPY --from=build /usr/local/bundle /usr/local/bundle
			COPY --from=build /rails /rails
			RUN groupadd --system --gid 1000 rails && useradd rails --uid 1000 --gid 1000 --create-home --shell /bin/bash \
			    && mkdir -p db log storage tmp && chown -R rails:rails db log storage tmp
			{dirs}USER 1000:1000
			EXPOSE {app.Port}
			CMD {ExecForm(app.StartCommand ?? "bin/rails server -b 0.0.0.0")}

			""";
	}

	static string Go(DeploymentPlan plan)
	{
		var app = plan.App;
		var version = app.RuntimeVersion ?? RuntimeDefaults.Go;
		var build = (app.BuildCommand ?? "go build -o /out/app .").Replace("go build", "CGO_ENABLED=0 go build", StringComparison.Ordinal);
		return $"""
			FROM golang:{version} AS build
			WORKDIR /src
			COPY go.mod go.sum* ./
			RUN --mount=type=cache,target=/go/pkg/mod go mod download
			COPY . .
			RUN --mount=type=cache,target=/go/pkg/mod --mount=type=cache,target=/root/.cache/go-build \
			    {build}

			FROM gcr.io/distroless/static-debian12:nonroot
			COPY --from=build /out/app /app
			USER nonroot:nonroot
			EXPOSE {app.Port}
			ENTRYPOINT ["/app"]

			""";
	}

	static string Java(DeploymentPlan plan)
	{
		var app = plan.App;
		var version = app.RuntimeVersion ?? RuntimeDefaults.Java;
		var maven = app.PackageManager == "maven";
		var wrapper = app.BuildCommand?.StartsWith("./", StringComparison.Ordinal) ?? false;
		var buildImage = wrapper ? $"eclipse-temurin:{version}-jdk" : maven ? $"maven:3-eclipse-temurin-{version}" : $"gradle:jdk{version}";
		var output = maven ? "target" : "build/libs";
		var cache = maven ? "/root/.m2" : "/root/.gradle";
		return $"""
			FROM {buildImage} AS build
			WORKDIR /src
			COPY . .
			RUN --mount=type=cache,target={cache} {app.BuildCommand} \
			    && find {output} -maxdepth 1 -name '*.jar' ! -name '*-plain.jar' ! -name '*-sources.jar' ! -name '*.original' -exec cp {"{}"} /app.jar \;

			FROM eclipse-temurin:{version}-jre
			RUN useradd --uid 10001 --create-home app
			WORKDIR /app
			COPY --from=build /app.jar /app/app.jar
			ENV JAVA_TOOL_OPTIONS="-XX:MaxRAMPercentage=75 -XX:+ExitOnOutOfMemoryError"
			USER 10001
			EXPOSE {app.Port}
			ENTRYPOINT ["java", "-jar", "/app/app.jar"]

			""";
	}

	static string Static(DeploymentPlan plan)
	{
		var app = plan.App;
		var sb = new StringBuilder();
		var built = app.BuildCommand is not null;
		if (built)
		{
			sb.AppendLine($"FROM node:{app.RuntimeVersion ?? RuntimeDefaults.Node}-slim AS build");
			sb.AppendLine("WORKDIR /app");
			sb.AppendLine("COPY package.json package-lock.json* yarn.lock* pnpm-lock.yaml* ./");
			sb.AppendLine("RUN corepack enable && if [ -f pnpm-lock.yaml ]; then pnpm install --frozen-lockfile; elif [ -f yarn.lock ]; then yarn install --frozen-lockfile; elif [ -f package-lock.json ]; then npm ci; else npm install; fi");
			sb.AppendLine("COPY . .");
			sb.AppendLine($"RUN {app.BuildCommand}");
			sb.AppendLine();
		}
		sb.AppendLine("FROM nginxinc/nginx-unprivileged:stable-alpine");
		sb.AppendLine("COPY <<'EOF' /etc/nginx/conf.d/default.conf");
		sb.AppendLine("server {");
		sb.AppendLine("    listen 8080;");
		sb.AppendLine("    root /usr/share/nginx/html;");
		sb.AppendLine("    server_tokens off;");
		sb.AppendLine("    location / { try_files $uri $uri/ /index.html; }");
		sb.AppendLine("    location ~* \\.(js|css|png|jpg|jpeg|gif|svg|ico|woff2?)$ { expires 30d; add_header Cache-Control \"public, immutable\"; }");
		sb.AppendLine("}");
		sb.AppendLine("EOF");
		var root = string.IsNullOrEmpty(app.DocumentRoot) ? "." : app.DocumentRoot;
		sb.AppendLine(built ? $"COPY --from=build /app/{root}/ /usr/share/nginx/html/" : $"COPY {root}/ /usr/share/nginx/html/");
		sb.AppendLine("EXPOSE 8080");
		sb.AppendLine("HEALTHCHECK --interval=30s --timeout=5s CMD wget -qO- http://127.0.0.1:8080/ >/dev/null || exit 1");
		return sb.ToString();
	}

	/// <summary>Creates persistent mount points owned by the runtime user, so fresh volumes are writable.</summary>
	static string MkdirFor(DeploymentPlan plan, string owner)
	{
		if (plan.Volumes.Count == 0)
		{
			return "";
		}
		var paths = string.Join(' ', plan.Volumes.Select(v => v.MountPath));
		var sb = new StringBuilder();
		sb.AppendLine("USER root");
		sb.AppendLine($"RUN mkdir -p {paths} && chown -R {owner}:{owner} {paths}");
		if (owner == "www-data")
		{
			// serversideup/php images run unprivileged as www-data by default.
			sb.AppendLine("USER www-data");
		}
		return sb.ToString();
	}

	static string ExecForm(string command)
	{
		var parts = command.Split(' ', StringSplitOptions.RemoveEmptyEntries);
		return "[" + string.Join(", ", parts.Select(p => "\"" + p.Replace("\"", "\\\"", StringComparison.Ordinal) + "\"")) + "]";
	}
}
